ORDER = ["LOCK", "PART", "INNER", "SPREAD", "BAD"]


def main() -> int:
    trace = Path("tooling/out/h39/h47holdout")
    rows = []
    for stem, (verdict, note) in sorted(AUDIT.items()):
        tp = trace / stem / "trace.json"
        t = json.loads(tp.read_text(encoding="utf-8")) if tp.exists() else {}
        rows.append({
            "image": stem + ".jpg",
            "verdict": verdict,
            "note": note,
            "provenance": t.get("provenance"),
            "gate_passed": t.get("gate_passed"),
            "gate_score": t.get("gate_score"),
        })

    counts = {k: sum(1 for r in rows if r["verdict"] == k) for k in ORDER}
    scored = [r for r in rows if r["verdict"] != "SPREAD"]
    lock = counts["LOCK"]
    total = len(rows)

    lines = [
        "# Holdout 42 - strict visual audit",
        "",
        f"{total} fresh photos (never used for tuning), detector build 0.3.16.",
        "",
        "| verdict | photos |",
        "|---|---|",
    ]
    for k in ORDER:
        lines.append(f"| {k} | {counts[k]} |")
    lines += [
        "",
        f"**{lock} / {total} ({100 * lock / total:.0f} %) locked the page on all four edges.**",
        "",
        f"Excluding the {counts['SPREAD']} photos where both leaves are fully visible and the target "
        f"leaf is undefined: **{lock} / {len(scored)} ordinary photos are clean "
        f"({100 * lock / len(scored):.0f} %)**.",
        "",
        "## Gate behaviour on this set",
        "",
    ]
    fails = [r for r in rows if r["gate_passed"] is False]
    hard = [r for r in rows if r["verdict"] in ("BAD", "INNER")]
    caught = [r for r in hard if r["gate_passed"] is False]
    lines += [
        f"* gate failed on {len(fails)} photos: "
        + ", ".join(f"`{r['image'][:-4]}`" for r in fails),
        f"* of the {len(hard)} hard failures (BAD + INNER), the gate flagged {len(caught)}",
        "* gate precision on this set: "
        + ("every flag was a real hard failure" if len(caught) == len(fails)
           else f"{len(fails) - (len(hard) - len(caught))} of {len(fails)} flags were real"),
    ]
    missed = [r for r in hard if r["gate_passed"] is not False]
    if missed:
        lines.append("* missed: " + ", ".join(
            f"`{r['image'][:-4]}` ({r['verdict']}, {r['provenance']})" for r in missed))

    lines += ["", "## Per photo", "",
              "| photo | provenance | gate | verdict | note |", "|---|---|---|---|---|"]
    for r in rows:
        gate = "pass" if r["gate_passed"] else "**FAIL**"
        lines.append(f"| `{r['image'][:-4]}` | {r['provenance']} | {gate} | "
                     f"{r['verdict']} | {r['note']} |")

    out = Path("docs/runs/holdout42-audit.md")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    Path("tooling/out/h47/audit.json").write_text(json.dumps(rows, indent=1), encoding="utf-8")
    print("\n".join(lines[:14]))
    print(f"-> {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
