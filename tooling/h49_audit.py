#!/usr/bin/env python3
"""
H49 - strict visual audit of the fresh 42-photo holdout.

Why an audit instead of an IoU oracle
-------------------------------------
The holdout was meant to be scored against SAM pseudo-GT. That oracle failed on this set: the
photos are framed tightly on the book, so SAM's frame-sized box prompt segmented the whole scene,
and every quad came back as the image border (measured: 39/42 quads had a corner on the frame
edge). Point prompts did better but still missed pages that are not white paper (one page is a
green workbook cover).

A pseudo-GT that is wrong on a fifth of the set produces a number, not a measurement. So the
holdout is scored by a strict visual audit instead, with the criterion stated up front and the
same criterion applied to every photo:

  LOCK    all four quad edges lie on the page boundary (within roughly 2 % of the page side)
  PART    the quad follows the page but one or more edges miss it by more than that
  INNER   the quad is entirely inside the page (the owner's reported "box inside the page")
  BAD     degenerate/self-intersecting quad, or the quad is not on a page at all
  SPREAD  the quad covers BOTH leaves of an open spread

SPREAD is not counted as a detector failure: when both pages are fully visible the owner has not
said which leaf is the target, so it is reported separately until that product decision is made.

Evidence: audit_holdout42_<n>.png contact sheets at 880 px per photo, generated by
`python tooling\\h47_montage.py --set holdout42 --lane h47holdout --cols 2 --rows 3 --width 880
 --prefix audit`. Verdicts below are keyed by image stem.

Honest limitation: this audit is a visual judgement, not an independent oracle. It is reproducible
(the sheets are fixed, the criterion is fixed) but it is made by the same assistant that wrote the
code, so it can be wrong in the detector's favour. It does not replace corner-level GT.
"""
