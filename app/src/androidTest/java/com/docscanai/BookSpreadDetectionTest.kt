/**
 * ============================================================================================
 * SUBTASK H29 — book-spread fixtures: the "one page of an open book" failure, measured.
 * ============================================================================================
 *
 * The owner's report was that the app sometimes keeps **more than the requested page** — an open
 * book is photographed with the facing page still in frame across a shadowed gutter, and the
 * detector returns the whole spread instead of the page that was asked for. The existing corpus
 * (DocUNet photographs) has no ground-truth corners, so it could never measure that: it only
 * counted detections.
 *
 * This class drives the REAL production detector ([`com.docscanai.capture.OpenCvQuadPageDetector`]
 * via [`ServiceLocator.pageDetector`]) on 9 synthetic book-spread scenes generated by
 * `tooling/h29_fixtures.py`, each rendered twice — at the 3024x4032 still resolution the import
 * path uses, and at the 1280x720 `ImageAnalysis` size the live path uses. Ground truth is exact by
 * construction (the homography that placed the page), which is the only way to score corner error
 * and "did it absorb the sliver" honestly.
 *
 * Three numbers per asset, which is what the subtask asks for:
 *  1. **detection rate** per variant (did the detector return a quad at all),
 *  2. **corner error** in pixels and as a percentage of the image diagonal,
 *  3. **sliver merge** — does the returned quad cover the facing page? Measured as the fraction of
 *     the ground-truth sliver covered by the detected quad (>= [SLIVER_COVER_MERGED] counts as a
 *     merge, i.e. the quad grew across the gutter to take the neighbour).
 *
 * The fixtures are synthetic, and the manifest says so in `provenance_rule`; they are not presented
 * as camera data. See `docs/DETECTOR_STRATEGY.md` (plan of record) and `docs/RESULTS.md` (H29).
 */
@RunWith(AndroidJUnit4::class)
class BookSpreadDetectionTest {

    companion object {
        private const val TAG = "DocScan"

        private const val ASSET_DIR = "bookspread"
        private const val MANIFEST = "$ASSET_DIR/book_spread_manifest.json"

        /** The manifest is the contract; if it silently shrinks, the measurement is worthless. */
        private const val MIN_ITEMS = 8

        /** At least this many fixtures must exercise the facing-page sliver (the failure itself). */
        private const val MIN_SLIVER_ITEMS = 4

        /** A detected quad covering at least this fraction of the GT sliver has absorbed it. */
        private const val SLIVER_COVER_MERGED = 0.50

        /** A quad this far outside the frame is not a sane detection on this dataset. */
        private const val SANE_SLACK = 0.06

        // -----------------------------------------------------------------------------------
        // Pinned gate — the H29 baseline measurement on the SHIPPED LCNet100 corner model, taken
        // from two independent instrumentation processes (H29 and H29B) that agreed to the last
        // digit: detected 18/18, mergedSlivers 7/12, meanCornerPct 3.9562, meanIouPage 0.8279.
        //
        // These are floors to hold, not goals: they describe a detector that is wrong on this
        // dataset, and the H29 remit is to beat them. When a winning candidate ships, TIGHTEN
        // these to the new measurement — a pin left at the old, worse number stops guarding the
        // improvement it was supposed to protect.
        // -----------------------------------------------------------------------------------

        /** Fraction of the 18 fixture assets the detector must return a quad on. */
        private const val PIN_DETECT_FRACTION = 1.00

        /**
         * Sliver assets (12 of the 18) allowed to absorb the facing page.
         *
         * H29 baseline: 7 (the failure). H30 with M-LSD on every detection: 2 on device.
         * **H31 = the STEP 3 acceptance floor, 2** — the trigger must not give the win back.
         */
        private const val PIN_MAX_MERGED_SLIVERS = 2

        /**
         * Mean corner error over the detected assets, percent of the diagonal.
         *
         * H29 baseline 3.9562; **H31 pins the STEP 3 acceptance floor, 3.5672** (the number H30
         * achieved on device and that the subtask names as the gate). The shipped schedule measures
         * **3.3495** (`tooling/out/h31/H31F`, `MlsdMode.REPAIR`) — comfortably inside it. The pin
         * deliberately sits at the acceptance floor and not at 3.3495: the floor is the contract, and
         * a gate 0.0005 below a single measurement would turn legitimate device-to-device jitter into
         * a red test. The achieved number is recorded in the H31 SUMMARY and in the `H31_QUALITY`
         * log line, which is where it belongs for trend-watching.
         */
        private const val PIN_MAX_MEAN_CORNER_PCT = 3.5672

        /**
         * Mean page IoU over the detected assets. H30 on device: 0.8442, and that is the STEP 3
         * floor; the shipped schedule measures 0.8593 on top of it.
         */
        private const val PIN_MIN_MEAN_IOU = 0.8442

        /**
         * H30 latency budgets, milliseconds. H31 re-reads them as **sequence** budgets: the
         * authoritative p95 gate lives in `MlsdCostBudgetTest`, over a 200-frame sequence, because
         * a per-call p95 can never be met by any schedule that occasionally invokes a 74 ms model.
         */
        private const val BUDGET_LIVE_EXTRA_MS = 30.0
        private const val BUDGET_STILL_EXTRA_MS = 60.0

        /** H31 STEP 3: average per-frame cost over the 18-asset pass (a coarse sanity gate). */
        private const val BUDGET_MEAN_EXTRA_MS = 15.0

        /**
         * The mode production actually runs.
         *
         * H30 measured M-LSD's quality win and its per-call cost (+73.68 ms p50 / +99.39 ms p95 on
         * a preview frame) and had to leave the feature OFF. H31 keeps the win and removes the
         * *rate*: `MlsdTrigger` runs the model only when the corner quad carries the merge
         * signature, only once the scene has settled, and at most once per `cadence` frames, with
         * the fold cached as geometry in between.
         *
         * `REPAIR` is the shipped mode, chosen from the numbers rather than from taste: H30's own
         * matrix has `merge_320` (repair) ahead of `fuse_320` (repair + candidate) on both headline
         * numbers, and the H31 corpus runs show the candidate growing an already-correct quad
         * (`syn_persp_mild_2`, 0.18 % -> 2.30 % corner error). `BOTH` is still measured here, so the
         * comparison stays visible in the log.
         */
        private val PRODUCTION_MODE = OpenCvQuadPageDetector.MlsdMode.REPAIR

        /**
         * ONE measurement pass, shared by every test in this class.
         *
         * The gate has to be computed from the same numbers that get logged, or the table and the
         * assertion can describe different runs. That is not hypothetical: the first version of
         * this class measured twice and the two passes reported `mergedSlivers=7/12` and `12/12`
         * for the same 18 images.
         */
        private val measuredScores =
            java.util.concurrent.ConcurrentHashMap<OpenCvQuadPageDetector.MlsdMode, List<Score>>()

        @JvmStatic
        @BeforeClass
        fun setUp() {
            NeuralRepro.setUp(enableXnnpack = false, tag = "BookSpreadDetectionTest/CPU-EP")
        }
    }

    // ==========================================================================================
    // Manifest model
    // ==========================================================================================

    /** One rendered canvas of one scene, with its exact ground truth. */
    private class Shot(
        val asset: String,
        val bytes: Long,
        val width: Int,
        val height: Int,
        val diagonal: Double,
        val page: List<PointF>,
        val spread: List<PointF>,
        val sliver: List<PointF>?
    )

    private class Fixture(
        val name: String,
        val variant: String,
        val side: String?,
        val sliverFraction: Double,
        val still: Shot,
        val preview: Shot
    ) {
        fun shot(canvas: String): Shot = if (canvas == CANVAS_STILL) still else preview

        companion object {
            const val CANVAS_STILL = "still"
            const val CANVAS_PREVIEW = "preview"
        }
    }

    /** One scored asset; the unit the head-to-head table is built from. */
    private class Score(
        val fixture: Fixture,
        val canvas: String,
        val detected: Boolean,
        val provenance: QuadProvenance,
        val meanCornerPx: Double,
        val maxCornerPx: Double,
        val sliverCovered: Double,
        val areaFrac: Double,
        val iouPage: Double,
        val millis: Double
    ) {
        /**
         * SUBTASK H31: did the M-LSD model actually run for this asset? Set by the measurement
         * driver from the schedule's own counter, so "did the trigger fire" is never inferred from
         * a timing difference.
         */
        var mlsdInvoked: Boolean = false

        /** A clean control: no facing page in the scene at all. */
        val isCleanPage: Boolean get() = fixture.sliverFraction <= 0.0
        val cornerPct: Double
            get() = 100.0 * meanCornerPx / (fixture.shot(canvas).diagonal.coerceAtLeast(1.0))

        val merged: Boolean
            get() = sliverCovered >= SLIVER_COVER_MERGED
    }

    // ==========================================================================================
    // 1) The fixture set itself must be trustworthy before it is allowed to score anything
    // ==========================================================================================

    @Test
    fun fixtureManifestIsConsistent() {
        val items = loadFixtures()
        assertTrue(
            "book-spread fixture set shrank: ${items.size} item(s) in assets/$MANIFEST, " +
                "need >= $MIN_ITEMS",
            items.size >= MIN_ITEMS
        )

        val sliverItems = items.filter { it.sliverFraction > 0.0 }
        assertTrue(
            "only ${sliverItems.size} fixture(s) carry a facing-page sliver; the failure under " +
                "test needs >= $MIN_SLIVER_ITEMS",
            sliverItems.size >= MIN_SLIVER_ITEMS
        )
        assertTrue(
            "sliver fixtures must cover both sides (sides=${sliverItems.map { it.side }})",
            sliverItems.any { it.side == "left" } && sliverItems.any { it.side == "right" }
        )

        val ctx = InstrumentationRegistry.getInstrumentation().context
        items.forEach { f ->
            listOf(Fixture.CANVAS_STILL to f.still, Fixture.CANVAS_PREVIEW to f.preview)
                .forEach { (canvas, s) ->
                    val where = "${f.name}/$canvas"
                    val onDisk = ctx.assets.open("$ASSET_DIR/${s.asset}").use { input ->
                        input.readBytes().size.toLong()
                    }
                    assertTrue(
                        "$where: asset bytes $onDisk != manifest ${s.bytes} — the manifest is " +
                            "stale, regenerate with `python tooling/h29_fixtures.py`",
                        onDisk == s.bytes
                    )
                    assertTrue("$where: page quad is not 4 points", s.page.size == 4)
                    assertTrue(
                        "$where: gt corners fall outside the ${s.width}x${s.height} canvas " +
                            "(${s.page})",
                        s.page.all {
                            it.x >= -2f && it.x <= s.width + 2f &&
                                it.y >= -2f && it.y <= s.height + 2f
                        }
                    )
                    val pageFrac = areaOf(s.page) / (s.width.toDouble() * s.height.toDouble())
                    assertTrue(
                        "$where: GT page area fraction $pageFrac is implausible (0.15..0.90)",
                        pageFrac in 0.15..0.90
                    )
                    // The sliver must be a real, thin neighbour: big enough to be visible, small
                    // enough that calling it a page is the error we are hunting.
                    s.sliver?.let { sl ->
                        val slFrac = areaOf(sl) / (s.width.toDouble() * s.height.toDouble())
                        assertTrue(
                            "$where: GT sliver area fraction $slFrac is not a sliver " +
                                "(0.004..0.40)",
                            slFrac in 0.004..0.40
                        )
                        val overlap = coverage(sl, s.page, s.width, s.height)
                        assertTrue(
                            "$where: GT sliver overlaps the GT page (${100.0 * overlap}%) — " +
                                "the fixture geometry is wrong",
                            overlap < 0.02
                        )
                    }
                    if (f.sliverFraction > 0.0) {
                        assertTrue(
                            "$where: a sliver fixture must carry a gt_sliver quad",
                            s.sliver != null
                        )
                    }
                    Log.i(
                        TAG,
                        "H29_SPREAD_FIXTURE name=${f.name} canvas=$canvas variant=${f.variant} " +
                            "side=${f.side} sliverFrac=${fmt(f.sliverFraction)} " +
                            "pageAreaFrac=${fmt(pageFrac)} bytes=${s.bytes}"
                    )
                }
        }
        Log.i(TAG, "H29_SPREAD_FIXTURE_RESULT items=${items.size} sliverItems=${sliverItems.size}")
    }

