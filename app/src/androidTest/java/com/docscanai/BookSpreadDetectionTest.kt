    private fun loadFixtures(): List<Fixture> {
        val ctx = InstrumentationRegistry.getInstrumentation().context
        val text = ctx.assets.open(MANIFEST).use { it.bufferedReader().readText() }
        val items = JSONObject(text).getJSONArray("items")
        return (0 until items.length()).map { i ->
            val o = items.getJSONObject(i)
            Fixture(
                name = o.getString("name"),
                variant = o.getString("variant"),
                side = if (o.isNull("sliver_side")) null else o.getString("sliver_side"),
                sliverFraction = o.optDouble("sliver_fraction", 0.0),
                still = shotOf(o.getJSONObject(Fixture.CANVAS_STILL)),
                preview = shotOf(o.getJSONObject(Fixture.CANVAS_PREVIEW))
            )
        }
    }

    private fun shotOf(o: JSONObject): Shot = Shot(
        asset = o.getString("asset"),
        bytes = o.getLong("asset_bytes"),
        width = o.getInt("width"),
        height = o.getInt("height"),
        diagonal = o.getDouble("diagonal"),
        page = points(o.getJSONArray("gt_page")),
        spread = points(o.getJSONArray("gt_spread")),
        sliver = if (o.isNull("gt_sliver")) null else points(o.getJSONArray("gt_sliver"))
    )

    private fun points(a: JSONArray): List<PointF> = (0 until a.length()).map { i ->
        val p = a.getJSONArray(i)
        PointF(p.getDouble(0).toFloat(), p.getDouble(1).toFloat())
    }

    private fun meanOf(v: List<Double>): Double =
        if (v.isEmpty()) 0.0 else v.sum() / v.size.toDouble()

    /**
     * `x,y;x,y;x,y;x,y` for the returned quad, so the on-device run can be compared corner for
     * corner with the offline replica (`tooling/h30_score.py`) instead of only in aggregate.
     */
    private fun quadString(q: Quad?): String = q?.let { quad ->
        listOf(quad.topLeft, quad.topRight, quad.bottomRight, quad.bottomLeft)
            .joinToString(";") { "${it.x.toInt()},${it.y.toInt()}" }
    } ?: "none"

    private fun fmt(v: Double): String = String.format(Locale.US, "%.4f", v)

    /** Quads of the last measurement, kept only so the sanity assertions can quote them. */
    private val LAST_QUADS = HashMap<Pair<String, String>, Quad>()
