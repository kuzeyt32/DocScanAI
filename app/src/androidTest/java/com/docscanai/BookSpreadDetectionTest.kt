    /**
     * Memoised measurement, **per M-LSD mode**. Every assertion for a given mode reads from one
     * pass, so the pinned gate and the logged table can never disagree — and the A/B
     * (`OFF` vs `BOTH`) is two independent passes over the same assets in the same process.
     */
    private fun scores(mode: OpenCvQuadPageDetector.MlsdMode = PRODUCTION_MODE): List<Score> {
        measuredScores[mode]?.let { return it }
        synchronized(this) {
            measuredScores[mode]?.let { return it }
            val fresh = measureAll(mode)
            measuredScores[mode] = fresh
            return fresh
        }
    }

    private fun measureAll(mode: OpenCvQuadPageDetector.MlsdMode): List<Score> {
        val ctx = InstrumentationRegistry.getInstrumentation().context
        val detector = ServiceLocator.pageDetector
        val out = ArrayList<Score>()
        (detector as? OpenCvQuadPageDetector)?.mlsdMode = mode
        LAST_QUADS.clear()
        Log.i(
            TAG,
            "H29_SPREAD_MODE mode=$mode mlsdModelPresent=${ServiceLocator.isMlsdModelPresent()} " +
                "trigger=${(detector as? OpenCvQuadPageDetector)?.let { MlsdTrigger.describe(it.mlsdPolicy) } ?: "-"}"
        )
        // NEVER call detector.release() here. `release()` sets `released = true` on the shared
        // ServiceLocator singleton and closes the ONNX sessions, after which resolveCornerModel()
        // returns null forever and every later detect() silently measures CLASSICAL_FALLBACK
        // instead of LCNet100. That is exactly what produced the "7 vs 12 merged slivers"
        // disagreement above — the second pass had lost the primary model, not the first one.
        loadFixtures().forEach { f ->
                listOf(Fixture.CANVAS_STILL, Fixture.CANVAS_PREVIEW).forEach { canvas ->
                    val s = f.shot(canvas)
                    // SUBTASK H31: every asset is a NEW page, so the trigger starts cold — which
                    // is exactly the app's situation when the user turns to the next spread. The
                    // still canvas is a capture (`Hint.STILL`: one attempt, no cadence); the
                    // preview canvas is a settled live frame.
                    (detector as? OpenCvQuadPageDetector)?.let { d ->
                        d.mlsdHint = if (canvas == Fixture.CANVAS_STILL) {
                            MlsdTrigger.Hint.STILL
                        } else {
                            MlsdTrigger.Hint(moving = false, settledFrames = 99, still = false)
                        }
                        d.mlsdSchedule.reset()
                    }
                    val bmp = decode(ctx, "$ASSET_DIR/${s.asset}")
                    if (bmp == null) {
                        Log.e(TAG, "H29_SPREAD name=${f.name} canvas=$canvas DECODE FAILED")
                        out.add(Score(f, canvas, false, QuadProvenance.UNKNOWN, Double.NaN,
                            Double.NaN, 0.0, -1.0, 0.0, 0.0))
                        return@forEach
                    }
                    try {
                        val before = (detector as? OpenCvQuadPageDetector)
                            ?.mlsdSchedule?.invocations ?: 0
                        val t0 = System.nanoTime()
                        val quad = runCatching { runBlocking { detector.detect(bmp) } }.getOrNull()
                        val ms = (System.nanoTime() - t0) / 1e6
                        val invoked = ((detector as? OpenCvQuadPageDetector)
                            ?.mlsdSchedule?.invocations ?: 0) > before
                        val prov = runCatching { detector.lastProvenance }
                            .getOrDefault(QuadProvenance.UNKNOWN)
                        if (quad == null) {
                            Log.i(
                                TAG,
                                "H29_SPREAD name=${f.name} canvas=$canvas variant=${f.variant} " +
                                    "detected=false prov=$prov ms=${fmt(ms)} mlsdInvoked=$invoked"
                            )
                            out.add(Score(f, canvas, false, prov, Double.NaN, Double.NaN, 0.0,
                                -1.0, 0.0, ms).also { it.mlsdInvoked = invoked })
                            return@forEach
                        }
                        LAST_QUADS[f.name to canvas] = quad
                        val pts = quad.points.map { PointF(it.x, it.y) }
                        val (meanPx, maxPx) = alignAndMeasure(pts, s.page)
                        val cover = s.sliver?.let { coverage(it, pts, s.width, s.height) } ?: 0.0
                        val areaFrac = areaOf(pts) / (s.width.toDouble() * s.height.toDouble())
                        val iou = iouOf(pts, s.page, s.width, s.height)
                        out.add(
                            Score(f, canvas, true, prov, meanPx, maxPx, cover, areaFrac, iou, ms)
                                .also { it.mlsdInvoked = invoked }
                        )
                        Log.i(
                            TAG,
                            "H29_SPREAD name=${f.name} canvas=$canvas variant=${f.variant} " +
                                "side=${f.side} mode=$mode detected=true prov=$prov " +
                                "meanCornerPx=${fmt(meanPx)} maxCornerPx=${fmt(maxPx)} " +
                                "cornerPct=${fmt(100.0 * meanPx / s.diagonal)} " +
                                "iouPage=${fmt(iou)} areaFrac=${fmt(areaFrac)} " +
                                "sliverCovered=${fmt(cover)} merged=${cover >= SLIVER_COVER_MERGED} " +
                                "ms=${fmt(ms)} mlsdInvoked=$invoked quad=${quadString(quad)} " +
                                "mlsd=${(detector as? OpenCvQuadPageDetector)?.lastMlsdLog ?: "-"}"
                        )
                    } finally {
                        bmp.recycle()
                    }
                }
            }
        return out
    }

    // ==========================================================================================
    // Geometry helpers (no OpenCV: pure android.graphics, so the metrics are platform-exact)
    // ==========================================================================================

    private fun decode(ctx: android.content.Context, path: String): Bitmap? = try {
        ctx.assets.open(path).use { BitmapFactory.decodeStream(it) }
    } catch (t: Throwable) {
        Log.e(TAG, "failed to decode assets/$path", t)
        null
    }

    /**
     * Mean and max corner distance after the best of the eight orderings that keep the quad a
     * closed polygon (4 rotations x 2 windings). Detectors are free to order corners differently;
     * scoring a reordering as a huge error would be a measurement bug, not a detector bug.
     */
    private fun alignAndMeasure(det: List<PointF>, gt: List<PointF>): Pair<Double, Double> {
        var bestMean = Double.MAX_VALUE
        var bestMax = Double.MAX_VALUE
        for (rev in 0..1) {
            val seq = if (rev == 0) det else det.reversed()
            for (shift in seq.indices) {
                var sum = 0.0
                var mx = 0.0
                for (i in gt.indices) {
                    val a = seq[(i + shift) % seq.size]
                    val b = gt[i]
                    val d = hypot((a.x - b.x).toDouble(), (a.y - b.y).toDouble())
                    sum += d
                    if (d > mx) mx = d
                }
                val mean = sum / gt.size
                if (mean < bestMean) {
                    bestMean = mean
                    bestMax = mx
                }
            }
        }
        return bestMean to bestMax
    }

    private fun pathOf(pts: List<PointF>): Path {
        val p = Path()
        p.moveTo(pts[0].x, pts[0].y)
        for (i in 1 until pts.size) p.lineTo(pts[i].x, pts[i].y)
        p.close()
        return p
    }

    private fun regionOf(pts: List<PointF>, w: Int, h: Int): Region {
        val r = Region()
        r.setPath(pathOf(pts), Region(0, 0, w, h))
        return r
    }

    private fun regionArea(r: Region): Double {
        var a = 0.0
        val it = RegionIterator(r)
        val rect = Rect()
        while (it.next(rect)) a += rect.width().toDouble() * rect.height().toDouble()
        return a
    }

    /** Area of [inner] covered by [outer], as a fraction of [inner]. */
    private fun coverage(inner: List<PointF>, outer: List<PointF>, w: Int, h: Int): Double {
        val ri = regionOf(inner, w, h)
        val base = regionArea(ri)
        if (base <= 0.0) return 0.0
        val ro = regionOf(outer, w, h)
        val inter = Region(ri)
        if (!inter.op(ro, Region.Op.INTERSECT)) return 0.0
        return (regionArea(inter) / base).coerceIn(0.0, 1.0)
    }

    private fun iouOf(a: List<PointF>, b: List<PointF>, w: Int, h: Int): Double {
        val ra = regionOf(a, w, h)
        val rb = regionOf(b, w, h)
        val inter = Region(ra)
        if (!inter.op(rb, Region.Op.INTERSECT)) return 0.0
        val ai = regionArea(inter)
        val union = regionArea(ra) + regionArea(rb) - ai
        return if (union <= 0.0) 0.0 else ai / union
    }

    private fun areaOf(pts: List<PointF>): Double {
        var sum = 0.0
        for (i in pts.indices) {
            val a = pts[i]
            val b = pts[(i + 1) % pts.size]
            sum += a.x.toDouble() * b.y.toDouble() - b.x.toDouble() * a.y.toDouble()
        }
        return kotlin.math.abs(sum) / 2.0
    }

